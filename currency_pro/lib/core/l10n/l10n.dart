class LocaleOption {
  const LocaleOption(this.code, this.nativeName, this.englishName);

  final String code;
  final String nativeName;
  final String englishName;

  bool get isSystem => code == AppLocales.systemCode;
}

class AppLocales {
  const AppLocales._();

  static const String systemCode = 'system';

  static const List<LocaleOption> options = <LocaleOption>[
    LocaleOption(systemCode, 'System default', 'Follow device'),
    LocaleOption('en', 'English', 'English'),
    LocaleOption('es', 'Español', 'Spanish'),
    LocaleOption('fr', 'Français', 'French'),
    LocaleOption('de', 'Deutsch', 'German'),
    LocaleOption('ar', 'العربية', 'Arabic'),
    LocaleOption('ur', 'اردو', 'Urdu'),
    LocaleOption('hi', 'हिन्दी', 'Hindi'),
    LocaleOption('zh', '中文', 'Chinese'),
    LocaleOption('pt', 'Português', 'Portuguese'),
    LocaleOption('tr', 'Türkçe', 'Turkish'),
    LocaleOption('id', 'Indonesia', 'Indonesian'),
    LocaleOption('it', 'Italiano', 'Italian'),
    LocaleOption('ru', 'Русский', 'Russian'),
    LocaleOption('ja', '日本語', 'Japanese'),
  ];

  static const List<Locale> materialLocales = <Locale>[
    Locale('en'),
    Locale('es'),
    Locale('fr'),
    Locale('de'),
    Locale('ar'),
    Locale('ur'),
    Locale('hi'),
    Locale('zh'),
    Locale('pt'),
    Locale('tr'),
    Locale('id'),
    Locale('it'),
    Locale('ru'),
    Locale('ja'),
  ];

  static String canonical(String code) {
    for (final LocaleOption o in options) {
      if (!o.isSystem && o.code == code) return code;
    }
    return 'en';
  }

  static String nativeName(String code) {
    for (final LocaleOption o in options) {
      if (o.code == code) return o.nativeName;
    }
    return code;
  }

  static Locale resolve(String localeCode, List<Locale> deviceLocales) {
    if (localeCode != systemCode) return Locale(canonical(localeCode));
    for (final Locale loc in deviceLocales) {
      for (final Locale supported in materialLocales) {
        if (supported.languageCode == loc.languageCode) return supported;
      }
    }
    return const Locale('en');
  }
}

